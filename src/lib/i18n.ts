function fill(base: Record<string, string>, extra: Record<string, string>) {
  return { ...base, ...extra };
}

for (const locale of LOCALES) {
  if (locale === "ru" || locale === "en") continue;
  const extra = visitorOverlays[locale] || {};
  dict[locale] = fill(locale === "uk" ? dict.ru : dict.en, extra);
}

export function detectLocale(input?: string | null): Locale {
  const raw = (input || "").toLowerCase();
  const code = raw.replace("_", "-").slice(0, 2);
  if ((LOCALES as readonly string[]).includes(code)) return code as Locale;
  return "en";
}

export function detectLocaleFromHeader(header?: string | null): Locale {
  if (!header) return "en";
  const first = header.split(",")[0]?.trim() || "";
  return detectLocale(first);
}

export function t(locale: Locale, key: string, vars?: Record<string, string | number>) {
  const table = dict[locale] || dict.en;
  let out = table[key] || dict.en[key] || dict.ru[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replaceAll(`{${k}}`, String(v));
    }
  }
  return out;
}

export function popupCopy(locale: Locale) {
  return {
    title: t(locale, "popup.title"),
    text: t(locale, "popup.text"),
    cta: t(locale, "popup.cta"),
    close: t(locale, "popup.close"),
  };
}
